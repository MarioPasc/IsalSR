"""Merge wl_subtree result folders into a unified directory tree.

Creates wl_subtree_full/ by symlinking (or copying) per-problem result
subtrees from wl_subtree, wl_subtree_hard, wl_subtree_cherrypicked, and
wl_subtree_roundoff. Only raw per-problem data is merged; analysis/,
figures/, slurm_logs/ are excluded (they will be regenerated by the
analysis pipeline).

Usage:
    python -m experiments.scripts.merge_results \
        --base-dir /media/.../real_benchmarks \
        --output-name wl_subtree_full
"""

from __future__ import annotations

import argparse
import logging
import os
import shutil
from pathlib import Path

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
log = logging.getLogger(__name__)

SOURCE_MAP: dict[str, dict[str, str | list[str] | None]] = {
    "wl_subtree": {
        "subpath": "",
        "benchmarks": ["nguyen", "feynman"],
    },
    "wl_subtree_hard": {
        "subpath": "models_hard",
        "benchmarks": ["hard"],
    },
    "wl_subtree_cherrypicked": {
        "subpath": "",
        "benchmarks": ["cherrypicked"],
    },
    "wl_subtree_roundoff": {
        "subpath": "",
        "benchmarks": ["roundoff"],
    },
}

METHODS = ["bingo", "udfs"]
SKIP_NAMES = frozenset({"analysis", "figures", "slurm_logs", "metadata.json"})


def merge_source(
    src_root: Path,
    dst_root: Path,
    benchmarks: list[str],
    use_copy: bool,
    flatten_to: str | None = None,
) -> dict[str, int]:
    """Merge one source's method/benchmark/problem trees into dst_root.

    Args:
        flatten_to: If set, all problems go into this single benchmark dir
            instead of preserving original benchmark subdirectories.

    Returns dict mapping "method/benchmark" to number of problems linked.
    """
    counts: dict[str, int] = {}

    for method in METHODS:
        for benchmark in benchmarks:
            src_bench = src_root / method / benchmark
            if not src_bench.is_dir():
                log.warning("Source benchmark dir missing: %s", src_bench)
                continue

            dst_bench_name = flatten_to if flatten_to else benchmark
            dst_bench = dst_root / method / dst_bench_name
            dst_bench.mkdir(parents=True, exist_ok=True)

            n = 0
            for problem_dir in sorted(src_bench.iterdir()):
                if not problem_dir.is_dir():
                    continue
                if problem_dir.name in SKIP_NAMES:
                    continue

                dst_problem = dst_bench / problem_dir.name
                if dst_problem.exists():
                    log.debug("Already exists, skipping: %s", dst_problem)
                    n += 1
                    continue

                if use_copy:
                    shutil.copytree(problem_dir, dst_problem)
                else:
                    os.symlink(problem_dir.resolve(), dst_problem)

                n += 1

            key = f"{method}/{benchmark}"
            counts[key] = n
            log.info("  %s: %d problems", key, n)

    return counts


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Merge wl_subtree result folders into a unified tree.",
    )
    parser.add_argument(
        "--base-dir",
        required=True,
        type=Path,
        help="Parent directory containing wl_subtree* folders (e.g., real_benchmarks/)",
    )
    parser.add_argument(
        "--output-name",
        default="wl_subtree_full",
        help="Name of the merged output directory (default: wl_subtree_full)",
    )
    parser.add_argument(
        "--sources",
        default="wl_subtree,wl_subtree_hard,wl_subtree_cherrypicked,wl_subtree_roundoff",
        help="Comma-separated source folder names",
    )
    parser.add_argument(
        "--copy",
        action="store_true",
        help="Copy files instead of creating symlinks (default: symlinks)",
    )
    parser.add_argument(
        "--flatten",
        default=None,
        metavar="NAME",
        help="Flatten all benchmarks into a single directory with this name "
        "(e.g., --flatten benchmark). Requires no problem name collisions.",
    )
    args = parser.parse_args()

    base_dir = args.base_dir.resolve()
    output_dir = base_dir / args.output_name
    sources = [s.strip() for s in args.sources.split(",")]

    log.info("Base dir: %s", base_dir)
    log.info("Output dir: %s", output_dir)
    log.info("Sources: %s", sources)
    log.info("Mode: %s", "copy" if args.copy else "symlink")
    if args.flatten:
        log.info("Flatten: all problems into '%s'", args.flatten)

    output_dir.mkdir(parents=True, exist_ok=True)
    all_counts: dict[str, int] = {}

    for source_name in sources:
        if source_name not in SOURCE_MAP:
            log.error("Unknown source: %s (known: %s)", source_name, list(SOURCE_MAP))
            continue

        cfg = SOURCE_MAP[source_name]
        subpath = cfg["subpath"]
        benchmarks = cfg["benchmarks"]
        assert isinstance(benchmarks, list)
        assert isinstance(subpath, str)

        src_root = base_dir / source_name
        if subpath:
            src_root = src_root / subpath

        if not src_root.is_dir():
            log.error("Source root missing: %s", src_root)
            continue

        log.info("=== Merging %s (%s) ===", source_name, src_root)
        counts = merge_source(src_root, output_dir, benchmarks, args.copy, flatten_to=args.flatten)
        all_counts.update(counts)

    log.info("")
    log.info("=" * 50)
    log.info("Merge complete. Summary:")
    log.info("%-20s %s", "Group", "N_problems")
    log.info("-" * 35)
    total = 0
    for key in sorted(all_counts):
        log.info("%-20s %d", key, all_counts[key])
        total += all_counts[key]
    log.info("-" * 35)
    log.info("%-20s %d", "TOTAL", total)
    log.info("Output: %s", output_dir)


if __name__ == "__main__":
    main()
