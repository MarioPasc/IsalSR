"""Locations and fixed constants of the SRBench black-box analysis.

The campaign corpus, the main campaign's analysis tree and the outputs of this
analysis all live on external storage; the code that produces them lives here.
Every entry point takes the three paths as arguments, so that another copy of
any of them can be pointed at without editing a path.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from benchmarks.datasets.srbench_blackbox import SRBENCH_BLACKBOX_DATASETS

_REVIEW_ROOT = Path("/media/mpascual/Sandisk2TB/research/ISAL/completed/isalsr/results/review")

#: Local copy of the 1,200-cell black-box corpus (read-only).
DEFAULT_CORPUS = _REVIEW_ROOT / "srbench_blackbox"

#: Analysis tree of the main three-arm campaign (read-only comparator).
DEFAULT_C2_ANALYSES = _REVIEW_ROOT / "c2_3arm" / "analyses"

#: Output tree of this analysis: tidy data, test records, values, tables.
DEFAULT_OUT = _REVIEW_ROOT / "srbench_blackbox_analysis"

#: Benchmark directory name under ``<corpus>/<method>/``.
BENCHMARK = "srbench_blackbox"

#: Orchestrator seeds of the campaign (PLAN D7: SRBench's ten trials).
SEEDS: tuple[int, ...] = tuple(range(1, 11))

#: Wall-clock budget per run, seconds (identical to the main campaign).
BUDGET_S = 43200.0

#: Bingo's evaluation cap, ``max_evals`` in both host configurations.
BINGO_MAX_EVALS = 100_000_000

#: Bingo stops before ``max_time`` when fewer than a quarter of a checkpoint
#: interval remain, so a time-limited Bingo run ends near 42,340 s rather than
#: at 43,200 s. A run at or above this fraction of the budget ended on time.
TIME_LIMIT_FRACTION = 0.97

#: PMLB dataset names, in the order of the suite module.
DATASETS: tuple[str, ...] = tuple(name for name, _, _ in SRBENCH_BLACKBOX_DATASETS)

#: Corpus directory name of each dataset (the orchestrator lower-cases slugs).
DATASET_DIR: dict[str, str] = {name: name.lower() for name in DATASETS}

#: Datasets whose primary description says they were generated, not measured.
#: SRBench flags only the Friedman generators, so these two pass its filter.
#: 529_pollen: OpenML 529, "This dataset is synthetic. It was generated by
#: David Coleman at RCA Laboratories" (also PMLB metadata.yaml at 8eec4f9).
#: banana: KEEL "artificial dataset where instances belong to several clusters
#: with a banana shape" (PMLB metadata.yaml on master, same 5300 x 2 KEEL data).
SYNTHETIC_DATASETS: frozenset[str] = frozenset({"529_pollen", "banana"})


def add_common_args(parser: argparse.ArgumentParser) -> argparse.ArgumentParser:
    """Attach ``--corpus``, ``--c2-analyses``, ``--out`` and ``--tables-dir``.

    Args:
        parser: Parser to extend.

    Returns:
        The same parser, for chaining.
    """
    parser.add_argument(
        "--corpus",
        type=Path,
        default=DEFAULT_CORPUS,
        help="Black-box corpus root holding <method>/srbench_blackbox/<dataset>/<arm>/seed_NN.",
    )
    parser.add_argument(
        "--c2-analyses",
        type=Path,
        default=DEFAULT_C2_ANALYSES,
        help="Main-campaign analysis tree (data/cells.csv, values/summary.json).",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="Output tree for this analysis; never inside the corpus.",
    )
    parser.add_argument(
        "--tables-dir",
        type=Path,
        default=None,
        help="Optional directory receiving a copy of every tab_supp_blackbox_*.tex.",
    )
    return parser
